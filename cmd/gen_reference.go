func init() {
	rootCmd.AddCommand(genReferenceCmd)
}

// genReferenceCmd writes the generated reference pages of the docs site.
var genReferenceCmd = &cobra.Command{
	Use:    "_gen_reference <dir>",
	Hidden: true,
	Short:  "Write the config and CLI reference pages into a directory",
	Args:   cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		dir := args[0]
		if err := utils.MkdirAllShared(dir); err != nil {
			return err
		}
		pages := map[string]string{
			"config.md": renderConfigReference(),
			"cli.md":    renderCLIReference(),
		}
		for name, text := range pages {
			f, err := utils.CreateFileWritable(filepath.Join(dir, name))
			if err != nil {
				return err
			}
			_, werr := f.WriteString(text)
			if cerr := f.Close(); werr != nil || cerr != nil {
				return fmt.Errorf("write %s: %w", name, errors.Join(werr, cerr))
			}
		}
		return nil
	},
}

// renderConfigReference writes the reference page: top-level settings first, then one section per prefix.
func renderConfigReference() string {
	var b strings.Builder
	b.WriteString("---\ntitle: Configuration Reference\ndescription: Every setting, what it accepts, its default, and the flags that set it.\n---\n\n")
	b.WriteString("<!-- Generated by `condatainer _gen_reference`. Edit the setting's declaration, not this file. -->\n\n")
	b.WriteString("To read or change a setting, see [Configuration](../guides/config.md).\n\n")
	b.WriteString("Each setting has an environment variable: `CNT_CONFIG_` followed by the setting name in capitals, with `.` written as `_`. Separate the values of a list with `|`.\n\n")

	b.WriteString("## General\n\n")
	for _, k := range settings.TopLevel() {
		writeReferenceKey(&b, k)
	}
	for _, prefix := range referencePrefixes() {
		fmt.Fprintf(&b, "## %s\n\nSettings that start with `%s.`.\n\n", strings.ToUpper(prefix[:1])+prefix[1:], prefix)
		for _, k := range settings.Section(prefix) {
			writeReferenceKey(&b, k)
		}
	}
	return b.String()
}

// referencePrefixes returns the first segment of every dotted setting name, sorted.
func referencePrefixes() []string {
	seen := map[string]bool{}
	for _, k := range settings.Keys() {
		if prefix, _, dotted := strings.Cut(k.Name, "."); dotted {
			seen[prefix] = true
		}
	}
	out := make([]string, 0, len(seen))
	for prefix := range seen {
		out = append(out, prefix)
	}
	sort.Strings(out)
	return out
}

func writeReferenceKey(b *strings.Builder, k *settings.Key) {
	fmt.Fprintf(b, "### `%s`\n\n%s\n\n", k.Name, referenceText(k.Help))
	fmt.Fprintf(b, "- **Takes:** %s\n- **Default:** %s\n- **Environment variable:** `%s`\n", k.Accepts(), referenceDefault(k), settings.EnvName(k.Name))
	if flags := k.FlagNames(); len(flags) > 0 {
		quoted := make([]string, len(flags))
		for i, name := range flags {
			quoted[i] = "`--" + name + "`"
		}
		fmt.Fprintf(b, "- **Flag:** %s\n", strings.Join(quoted, ", "))
	}
	b.WriteString("\n")
}

// referenceDefault words a default for the page.
//   - A default that is computed from the environment has no fixed text, so the page says so.
func referenceDefault(k *settings.Key) string {
	switch {
	case len(k.DefaultList) > 0:
		quoted := make([]string, len(k.DefaultList))
		for i, v := range k.DefaultList {
			quoted[i] = "`" + v + "`"
		}
		return strings.Join(quoted, ", ")
	case k.Default != "":
		return "`" + referenceValue(k) + "`"
	case k.DefaultText() != "":
		return "Depends on the environment."
	}
	return "Empty."
}

// referenceValue words a fixed default as the user writes it.
//   - A size or a number of days reads as `12GB` or `1d`. Any other kind shows its stored text.
func referenceValue(k *settings.Key) string {
	if kind := k.Kind(); kind == "memory" || kind == "days" {
		return k.Show(k.Default)
	}
	return k.Default
}

var referenceCode = regexp.MustCompile(`--[a-z][a-z-]*|\$[A-Za-z_]+(/[A-Za-z_./-]*[A-Za-z_])?`)

// referenceText puts a flag or a variable in code font, so the page keeps the two dashes of a flag as typed.
//   - Text already between backticks is left as it is.
func referenceText(text string) string {
	parts := strings.Split(text, "`")
	for i := 0; i < len(parts); i += 2 {
		parts[i] = referenceCode.ReplaceAllString(parts[i], "`$0`")
	}
	return strings.Join(parts, "`")
}

// renderCLIReference writes the reference page: the global flags, then each visible command, with subcommands one heading level down.
func renderCLIReference() string {
	var b strings.Builder
	b.WriteString("---\ntitle: CLI Reference\ndescription: Every command, its usage, its flags and examples.\ntableOfContents:\n  maxHeadingLevel: 2\n---\n\n")
	b.WriteString("<!-- Generated by `condatainer _gen_reference`. Edit the command's help, not this file. -->\n\n")
	b.WriteString("Every command also takes `-h, --help`, which prints the same text as this page.\n\n")
	b.WriteString("## Global flags\n\nEvery command takes these flags.\n\n")
	b.WriteString(cliFlagSections("Flags:\n" + rootCmd.PersistentFlags().FlagUsages())[0].markdown())
	for _, c := range rootCmd.Commands() {
		writeCLICommand(&b, c, 2)
	}
	return b.String()
}

func writeCLICommand(b *strings.Builder, c *cobra.Command, level int) {
	if !c.IsAvailableCommand() {
		return
	}
	path := strings.TrimPrefix(c.CommandPath(), rootCmd.Name()+" ")
	fmt.Fprintf(b, "%s %s\n\n", strings.Repeat("#", level), path)
	description := c.Long
	if description == "" {
		description = c.Short
	}
	b.WriteString(cliMarkdown(description) + "\n\n")
	fmt.Fprintf(b, "```text\n%s\n```\n\n", cliUsage(c))
	if len(c.Aliases) > 0 {
		aliases := make([]string, len(c.Aliases))
		for i, a := range c.Aliases {
			aliases[i] = "`" + a + "`"
		}
		fmt.Fprintf(b, "Aliases: %s.\n\n", strings.Join(aliases, ", "))
	}
	if example := cliDedent(c.Example); example != "" {
		fmt.Fprintf(b, "**Examples**\n\n```bash\n%s\n```\n\n", example)
	}
	for _, section := range cliFlagSections(commandHelp(c)) {
		b.WriteString(section.markdown())
	}
	for _, sub := range c.Commands() {
		writeCLICommand(b, sub, level+1)
	}
}

// cliUsage returns the usage line: the command path, then the arguments of its Use text.
func cliUsage(c *cobra.Command) string {
	if _, args, ok := strings.Cut(c.Use, " "); ok {
		return c.CommandPath() + " " + args
	}
	return c.CommandPath()
}

// commandHelp returns what --help prints for c, without the global flags.
func commandHelp(c *cobra.Command) string {
	var out bytes.Buffer
	c.SetOut(&out)
	defer c.SetOut(nil)
	c.InitDefaultHelpFlag() // cobra adds -h once a command has been run, so add it for every command alike
	_ = c.Help()
	help := out.String()
	if i := strings.Index(help, "\nGlobal Flags:\n"); i >= 0 {
		help = help[:i]
	}
	return strings.TrimRight(help, "\n") + "\n"
}

// cliFlags is one titled group of flags, as --help prints it.
type cliFlags struct {
	title string
	lines []string
}

var cliFlagLine = regexp.MustCompile(`^\s+(?:(-[A-Za-z]), )?(--[A-Za-z0-9-]+)(?: (\S+))?\s{2,}(.+)$`)

// cliFlagSections reads the flag groups out of help text, in the order printed.
//   - A group is a line that ends in "Flags:", followed by flag lines up to a blank line. The -h flag is left out.
func cliFlagSections(help string) []cliFlags {
	var out []cliFlags
	lines := strings.Split(help, "\n")
	for i := 0; i < len(lines); i++ {
		title, ok := strings.CutSuffix(lines[i], "Flags:")
		if !ok || strings.HasPrefix(lines[i], " ") {
			continue
		}
		group := cliFlags{title: strings.TrimSpace(title) + " flags"}
		if group.title == " flags" || group.title == "flags" {
			group.title = "Flags"
		}
		for i++; i < len(lines) && lines[i] != ""; i++ {
			if m := cliFlagLine.FindStringSubmatch(lines[i]); m != nil && m[2] == "--help" {
				continue
			}
			group.lines = append(group.lines, lines[i])
		}
		if len(group.lines) > 0 {
			out = append(out, group)
		}
	}
	return out
}

// markdown writes the group as a table, or as a text block when a line is not a flag line.
func (g cliFlags) markdown() string {
	var b strings.Builder
	fmt.Fprintf(&b, "**%s**\n\n| Flag | Description |\n|---|---|\n", g.title)
	for _, line := range g.lines {
		m := cliFlagLine.FindStringSubmatch(line)
		if m == nil {
			return fmt.Sprintf("**%s**\n\n```text\n%s\n```\n\n", g.title, strings.Join(g.lines, "\n"))
		}
		spec := m[2]
		if m[1] != "" {
			spec = m[1] + ", " + spec
		}
		if m[3] != "" {
			spec += " " + m[3]
		}
		fmt.Fprintf(&b, "| `%s` | %s |\n", spec, strings.ReplaceAll(cliEscape(m[4]), "|", `\|`))
	}
	return b.String() + "\n"
}

// cliMarkdown turns help text into Markdown.
//   - Lines indented by two spaces or more are laid out for the terminal, so a run of them becomes a text block.
//   - Other lines keep their line breaks, and a flag or a bracket cannot start a tag or an emphasis.
func cliMarkdown(text string) string {
	lines := strings.Split(strings.TrimRight(text, "\n"), "\n")
	indented := func(l string) bool { return strings.HasPrefix(l, "  ") && strings.TrimSpace(l) != "" }
	plain := func(l string) bool { return l != "" && !indented(l) && !strings.HasPrefix(l, "- ") }
	var out []string
	for i := 0; i < len(lines); {
		if indented(lines[i]) {
			j := i
			for j < len(lines) && indented(lines[j]) {
				j++
			}
			out = append(out, "", "```text")
			out = append(out, lines[i:j]...)
			out = append(out, "```", "")
			i = j
			continue
		}
		if i > 0 && strings.HasPrefix(lines[i-1], "- ") && plain(lines[i]) {
			out = append(out, "") // a list ends before a line that is not an item
		}
		line := cliEscape(lines[i])
		if plain(lines[i]) && i+1 < len(lines) && plain(lines[i+1]) {
			line += "  "
		}
		out = append(out, line)
		i++
	}
	return strings.TrimSpace(regexp.MustCompile(`\n{3,}`).ReplaceAllString(strings.Join(out, "\n"), "\n\n"))
}

// cliEscape puts flags in code font, and keeps the rest outside backticks from starting a tag or an emphasis.
func cliEscape(text string) string {
	parts := strings.Split(referenceText(text), "`")
	for i := 0; i < len(parts); i += 2 {
		parts[i] = strings.NewReplacer("<", `\<`, "*", `\*`).Replace(parts[i])
	}
	return strings.Join(parts, "`")
}

// cliDedent removes the indentation every line of an example shares.
func cliDedent(text string) string {
	lines := strings.Split(strings.Trim(text, "\n"), "\n")
	indent := -1
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			continue
		}
		if n := len(l) - len(strings.TrimLeft(l, " ")); indent < 0 || n < indent {
			indent = n
		}
	}
	for i, l := range lines {
		if len(l) >= indent && indent > 0 {
			lines[i] = l[indent:]
		}
	}
	return strings.TrimSpace(strings.Join(lines, "\n"))
}
